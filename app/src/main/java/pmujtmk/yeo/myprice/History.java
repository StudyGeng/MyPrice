package pmujtmk.yeo.myprice;

public class History {
    String ID, StoreName, Membership, Budget, TotalSpend, TotalDiscount, Date;

    public History(String ID, String StoreName, String Membership, String Budget, String TotalSpend, String TotalDiscount, String Date){
        this.ID = ID;
        this.StoreName = StoreName;
        this. Membership = Membership;
        this.Budget = Budget;
        this.TotalSpend = TotalSpend;
        this.TotalDiscount = TotalDiscount;
        this.Date = Date;
    }
}
